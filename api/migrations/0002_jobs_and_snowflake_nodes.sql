-- PLAN.md §2.1 items 2 and 3: Snowflake node-id leases and the Postgres job queue.

CREATE TABLE IF NOT EXISTS snowflake_nodes (
    node_id SMALLINT NOT NULL PRIMARY KEY CHECK (node_id BETWEEN 0 AND 1023),
    holder TEXT NOT NULL,
    heartbeat_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 5,
    locked_by TEXT,
    locked_at TIMESTAMPTZ,
    last_error TEXT,
    done_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- the claim query scans only runnable jobs
CREATE INDEX IF NOT EXISTS jobs_runnable ON jobs (run_at, id)
    WHERE done_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS jobs_kind ON jobs (kind);

-- The accepted file types (PLAN.md "Accepted file types"): images (HEIC, AVIF, TIFF, PSD and
-- camera raw included), video, audio, documents, data, archives, text and source code, fonts and
-- 3D models. Executables, installers, Windows scripts, Java, disk images, macro-enabled Office
-- files and other malware-style types are left out, with their extensions.
--
-- These tables are the allowlist: an upload keeps its declared type if it's listed here, else
-- takes the type of its extension; a file matching neither is refused (INVALID_MIMETYPE,
-- utils/uploading.py resolve_name). Bytes aren't sniffed yet, so a declared type is trusted.
--
-- Each type is one canonical name with every extension it's known by, preferred first
-- (priority 1: the extension a file gets when it has none; the others 0). Another name for a
-- type (an alias) comes after all the canonical rows, because an extension on its own resolves
-- to its first row (db/queries.py get_extension); so `.jpg` on its own is image/jpeg, while an
-- upload declared image/pjpeg keeps that name. Aliases browsers send for a type whose
-- extension is listed (audio/x-m4a, application/x-zip-compressed, ...) aren't needed: unknown
-- names fall back to the extension. `flags` stays 0: nothing reads it yet.


-- A text file sent as text/plain keeps its own extension (`notes.py` stays `.py`, as text/plain,
-- instead of becoming `notes.py.txt`): text/plain also takes every other text extension, after
-- the rows above.
INSERT INTO mimetype_extensions (mimetype_id, extension, priority)
SELECT 'text/plain', e.extension, 0
FROM mimetype_extensions AS e JOIN mimetypes AS m ON m.id = e.mimetype_id
WHERE m.type_id = 'text' AND m.id <> 'text/plain'
ORDER BY e.ctid;

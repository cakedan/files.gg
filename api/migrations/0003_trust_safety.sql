-- Trust & safety (docs/redesign/contracts/milestone-4.md §1): scan state per content, moderation
-- state per file and album, perceptual hashes, blocked hashes, staff, reports, cases, notices,
-- restrictions, bans, the audit log and evidence holds.
--
-- A fresh launch (milestone-4 §0): the tables are empty, so new NOT NULL columns need no backfill.
-- Ids of the new tables are identity columns, except reports (Snowflake, minted by the API, so a
-- reporter can't count reports from their ids). Every target reference is a real foreign key;
-- audit and history references are ON DELETE SET NULL so the trail survives deletions (PLAN.md
-- schema fix 3), which is why "exactly one target" checks below are "at most one": a target that
-- blob garbage collection deleted leaves its case or report without one.

-- the scan, per content (§2) -------------------------------------------------------------------------

ALTER TABLE file_hashes
    -- pending -> passed / flagged / held / blocked (§2.1)
    ADD COLUMN scan_state text NOT NULL DEFAULT 'pending'
        CHECK (scan_state IN ('pending', 'passed', 'flagged', 'held', 'blocked')),
    -- the reason code (§2.3) when flagged, held or blocked
    ADD COLUMN scan_reason text CHECK (scan_reason IN ('csam_match', 'hash_list', 'pdq_near_match', 'malware',
        'unwanted_software', 'blocked_type', 'archive_bomb', 'pdf_dangerous', 'pdf_javascript', 'polyglot_archive',
        'web_risk')),
    -- the last scan's results (§2.8)
    ADD COLUMN scan jsonb,
    ADD COLUMN scanned_at timestamptz,
    ADD COLUMN next_rescan_at timestamptz,
    ADD COLUMN nsfw_score real CHECK (nsfw_score >= 0 AND nsfw_score <= 1),
    ADD COLUMN nsfw_auto boolean NOT NULL DEFAULT false,
    -- false when an image or video couldn't be decoded for matching: served as an attachment only
    ADD COLUMN serve_inline boolean NOT NULL DEFAULT true,
    ADD CONSTRAINT file_hashes_scan_reason CHECK ((scan_state IN ('flagged', 'held', 'blocked')) = (scan_reason IS NOT NULL));
-- the sweeper and the stalled count (pending hashes), and the rescan scheduler
CREATE INDEX file_hashes_pending ON file_hashes (id) WHERE scan_state = 'pending';
CREATE INDEX file_hashes_next_rescan ON file_hashes (next_rescan_at) WHERE next_rescan_at IS NOT NULL;

-- Meta's PDQ of every image a scan matched (§3.4); `frame` numbers them in scan order
CREATE TABLE file_hash_pdq (
    hash_id bigint NOT NULL REFERENCES file_hashes (id) ON DELETE CASCADE,
    frame integer NOT NULL CHECK (frame >= 0),
    pdq bit(256) NOT NULL,
    quality smallint NOT NULL CHECK (quality BETWEEN 0 AND 100),
    PRIMARY KEY (hash_id, frame)
);


-- staff (§9.1) ----------------------------------------------------------------------------------------

CREATE TABLE staff (
    user_id bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('moderator', 'admin')),
    child_safety boolean NOT NULL DEFAULT false,
    granted_by bigint REFERENCES users (id) ON DELETE SET NULL,
    granted_at timestamptz NOT NULL DEFAULT now()
);


-- the audit log (§9.5) ---------------------------------------------------------------------------------
-- Append-only: the app never updates or deletes rows (only ON DELETE SET NULL clears a reference
-- whose target was deleted). No trigger enforces it: the schema has no triggers or functions of its
-- own (milestone-3 §0); tests/test_safety.py checks the app's SQL never writes to it but by INSERT.

CREATE TABLE moderation_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    actor_kind text NOT NULL CHECK (actor_kind IN ('staff', 'system', 'cli')),
    action text NOT NULL CHECK (action ~ '^[a-z_]{1,40}$'),
    rule text,
    file_id bigint REFERENCES files (id) ON DELETE SET NULL,
    album_id bigint REFERENCES albums (id) ON DELETE SET NULL,
    user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    hash_id bigint REFERENCES file_hashes (id) ON DELETE SET NULL,
    -- these three get their foreign keys once their tables exist (below)
    report_id bigint,
    case_id bigint,
    warning_id bigint,
    -- staff-only
    note text CHECK (char_length(note) <= 2000),
    details jsonb,
    -- set when the row belongs to a child-safety case: only child-safety staff see it
    child_safety boolean NOT NULL DEFAULT false,
    reverses_action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX moderation_actions_case ON moderation_actions (case_id, id) WHERE case_id IS NOT NULL;
CREATE INDEX moderation_actions_file ON moderation_actions (file_id, id) WHERE file_id IS NOT NULL;
CREATE INDEX moderation_actions_album ON moderation_actions (album_id, id) WHERE album_id IS NOT NULL;
CREATE INDEX moderation_actions_user ON moderation_actions (user_id, id) WHERE user_id IS NOT NULL;
CREATE INDEX moderation_actions_hash ON moderation_actions (hash_id, id) WHERE hash_id IS NOT NULL;
CREATE INDEX moderation_actions_actor ON moderation_actions (actor_user_id, id) WHERE actor_user_id IS NOT NULL;
CREATE INDEX moderation_actions_action ON moderation_actions (action, id);



-- blocked content (§1, §3.6, §9.3) -------------------------------------------------------------------
-- Survives blob garbage collection, so re-uploads stay blocked.

CREATE TABLE blocked_hashes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blake2b text NOT NULL,
    sha1 text NOT NULL,
    md5 text NOT NULL,
    size bigint,
    reason text NOT NULL CHECK (reason IN ('csam', 'ncii', 'terrorism', 'malware', 'moderator')),
    source text NOT NULL CHECK (source IN ('photodna', 'standin', 'staff', 'clamav')),
    action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (blake2b, sha1, md5)
);

CREATE TABLE blocked_hash_pdq (
    blocked_hash_id bigint NOT NULL REFERENCES blocked_hashes (id) ON DELETE CASCADE,
    frame integer NOT NULL CHECK (frame >= 0),
    pdq bit(256) NOT NULL,
    quality smallint NOT NULL CHECK (quality BETWEEN 0 AND 100),
    PRIMARY KEY (blocked_hash_id, frame)
);


-- files, uploads and albums (§1) --------------------------------------------------------------------------

ALTER TABLE files
    ADD COLUMN moderation_state text NOT NULL DEFAULT 'visible' CHECK (moderation_state IN ('visible', 'hidden', 'removed')),
    -- the rule (§8.1) behind the last hide or remove
    ADD COLUMN moderation_rule text,
    ADD COLUMN moderated_at timestamptz,
    -- the last hide was automatic (report thresholds, P0 reports, CSAM): the owner's reason is `review`
    ADD COLUMN moderation_auto boolean NOT NULL DEFAULT false,
    -- marked by the uploader
    ADD COLUMN nsfw_marked boolean NOT NULL DEFAULT false,
    -- set by staff or by report thresholds
    ADD COLUMN nsfw_override text CHECK (nsfw_override IN ('nsfw', 'safe')),
    ADD COLUMN nsfw_override_source text CHECK (nsfw_override_source IN ('moderator', 'reports')),
    -- why deleted_at was set: NULL (owner or expiry), 'moderator', or an upload-rejection code (§2.5)
    ADD COLUMN deleted_reason text CHECK (deleted_reason IN ('moderator', 'FILE_BLOCKED', 'MALWARE_DETECTED',
        'FILE_TYPE_NOT_ALLOWED', 'NSFW_REQUIRES_ACCOUNT', 'ENCRYPTED_ARCHIVE_REQUIRES_ACCOUNT')),
    -- §1 "IP hashes" and §3.6: cleared after ABUSE_IP_KEEP_DAYS
    ADD COLUMN uploader_abuse_ip_hash bytea,
    ADD COLUMN uploader_ip_sealed bytea,
    -- when the classifier marked this signed-in file that its uploader hadn't (§4.3, the "unmarked" rule)
    ADD COLUMN nsfw_unmarked_at timestamptz,
    ADD CONSTRAINT files_nsfw_override_source CHECK ((nsfw_override IS NULL) = (nsfw_override_source IS NULL));
CREATE INDEX files_moderation ON files (moderation_state) WHERE moderation_state <> 'visible';
CREATE INDEX files_abuse_ip ON files (uploader_abuse_ip_hash) WHERE uploader_abuse_ip_hash IS NOT NULL;
CREATE INDEX files_sealed_ip ON files (id) WHERE uploader_ip_sealed IS NOT NULL;
CREATE INDEX files_nsfw_unmarked ON files (user_id, nsfw_unmarked_at) WHERE nsfw_unmarked_at IS NOT NULL;
CREATE INDEX files_rejected ON files (deleted_at) WHERE deleted_reason IS NOT NULL;

ALTER TABLE upload_sessions
    ADD COLUMN nsfw_marked boolean NOT NULL DEFAULT false,
    ADD COLUMN owner_abuse_ip_hash bytea,
    ADD COLUMN owner_ip_sealed bytea;

ALTER TABLE albums
    -- `nsfw` now means marked (by the owner or staff), not derived (§4.4)
    ADD COLUMN nsfw_source text CHECK (nsfw_source IN ('owner', 'moderator')),
    ADD COLUMN moderation_rule text,
    ADD COLUMN moderated_at timestamptz,
    ADD COLUMN moderation_auto boolean NOT NULL DEFAULT false,
    -- Web Risk hits in its title, description and captions (§5.7), as [{url, threat_types, expires_at}]:
    -- a warning may be shown only while its match is within Google's expireTime, so payloads list only
    -- the fresh ones (resolves §5.7's open item; a jsonb list instead of the contract's text[])
    ADD COLUMN link_warnings jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(link_warnings) = 'array'),
    -- why deleted_at was set: NULL (the owner or the reaper) or 'moderator' (§9.3 `delete`)
    ADD COLUMN deleted_reason text CHECK (deleted_reason IN ('moderator')),
    ADD CONSTRAINT albums_nsfw_source CHECK (nsfw = (nsfw_source IS NOT NULL));


-- notices, restrictions and bans (§8, §9.3) ----------------------------------------------------------------

CREATE TABLE user_warnings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL,
    -- the action the notice is about (a snapshot: the audit row may outlive nothing else)
    action text NOT NULL,
    rule text NOT NULL,
    message text CHECK (char_length(message) <= 2000),
    -- a snapshot: { kind, id, vanity?, name? }
    target jsonb NOT NULL,
    appealable boolean NOT NULL,
    counts_as_strike boolean NOT NULL DEFAULT false,
    acknowledged_at timestamptz,
    appeal_state text NOT NULL DEFAULT 'none' CHECK (appeal_state IN ('none', 'open', 'granted', 'denied')),
    appeal_message text CHECK (char_length(appeal_message) <= 2000),
    appeal_counter_notice jsonb,
    -- staff's reply to a decided appeal
    appeal_reply text CHECK (char_length(appeal_reply) <= 2000),
    appealed_at timestamptz,
    appeal_decided_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_warnings_user ON user_warnings (user_id, id DESC);
CREATE INDEX user_warnings_strikes ON user_warnings (user_id, created_at) WHERE counts_as_strike;

ALTER TABLE moderation_actions ADD FOREIGN KEY (warning_id) REFERENCES user_warnings (id) ON DELETE SET NULL;

CREATE TABLE user_restrictions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('uploads', 'suspended')),
    rule text NOT NULL,
    action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL,
    -- the notice that explains it, when there is one
    warning_id bigint REFERENCES user_warnings (id) ON DELETE SET NULL,
    starts_at timestamptz NOT NULL DEFAULT now(),
    -- NULL = until lifted
    ends_at timestamptz,
    lifted_at timestamptz,
    lifted_by_action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL
);
CREATE INDEX user_restrictions_active ON user_restrictions (user_id) WHERE lifted_at IS NULL;

CREATE TABLE bans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint bigint,
    abuse_ip_hash bytea,
    rule text NOT NULL,
    action_id bigint REFERENCES moderation_actions (id) ON DELETE SET NULL,
    -- where staff took it from ({file_id}, {report_id} or {fingerprint}); staff never see the hash
    source jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- NULL = until lifted
    expires_at timestamptz,
    lifted_at timestamptz,
    CHECK (num_nonnulls(fingerprint, abuse_ip_hash) = 1)
);
CREATE INDEX bans_fingerprint ON bans (fingerprint) WHERE fingerprint IS NOT NULL AND lifted_at IS NULL;
CREATE INDEX bans_ip ON bans (abuse_ip_hash) WHERE abuse_ip_hash IS NOT NULL AND lifted_at IS NULL;


-- cases, reports and flags (§7, §9.2) -------------------------------------------------------------------------

CREATE TABLE moderation_cases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('file', 'album', 'user', 'hash', 'bug', 'appeal')),
    -- P0 (0) to P3 (3): the highest of its open parts
    priority smallint NOT NULL CHECK (priority BETWEEN 0 AND 3),
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    file_id bigint REFERENCES files (id) ON DELETE SET NULL,
    album_id bigint REFERENCES albums (id) ON DELETE SET NULL,
    user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    hash_id bigint REFERENCES file_hashes (id) ON DELETE SET NULL,
    warning_id bigint REFERENCES user_warnings (id) ON DELETE SET NULL,
    -- only child-safety staff see it
    child_safety boolean NOT NULL DEFAULT false,
    needs_second_review boolean NOT NULL DEFAULT false,
    assignee_id bigint REFERENCES users (id) ON DELETE SET NULL,
    claimed_at timestamptz,
    outcome text CHECK (outcome IN ('actioned', 'dismissed')),
    outcome_reason text CHECK (char_length(outcome_reason) <= 2000),
    -- the CyberTipline report, filed by hand and recorded (§3.6)
    cybertip_report_id text CHECK (char_length(cybertip_report_id) <= 64),
    cybertip_filed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    closed_at timestamptz,
    CHECK (num_nonnulls(file_id, album_id, user_id, hash_id, warning_id) <= 1),
    CHECK ((status = 'closed') = (closed_at IS NOT NULL))
);
-- one open case per target
CREATE UNIQUE INDEX moderation_cases_open_file ON moderation_cases (file_id) WHERE status = 'open' AND kind = 'file';
CREATE UNIQUE INDEX moderation_cases_open_album ON moderation_cases (album_id) WHERE status = 'open' AND kind = 'album';
CREATE UNIQUE INDEX moderation_cases_open_user ON moderation_cases (user_id) WHERE status = 'open' AND kind = 'user';
CREATE UNIQUE INDEX moderation_cases_open_hash ON moderation_cases (hash_id) WHERE status = 'open' AND kind = 'hash';
CREATE UNIQUE INDEX moderation_cases_open_appeal ON moderation_cases (warning_id) WHERE status = 'open' AND kind = 'appeal';
-- the queue: P0 first, then oldest first
CREATE INDEX moderation_cases_queue ON moderation_cases (priority, created_at, id) WHERE status = 'open';
CREATE INDEX moderation_cases_assignee ON moderation_cases (assignee_id) WHERE status = 'open';

ALTER TABLE moderation_actions ADD FOREIGN KEY (case_id) REFERENCES moderation_cases (id) ON DELETE SET NULL;

CREATE TABLE reports (
    -- a Snowflake id (the API mints it)
    id bigint PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('file', 'album', 'user', 'bug')),
    file_id bigint REFERENCES files (id) ON DELETE SET NULL,
    album_id bigint REFERENCES albums (id) ON DELETE SET NULL,
    user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    -- the target's vanity when it was reported, for the reporter's view once the target is gone
    target_vanity text,
    album_part text CHECK (album_part IN ('whole', 'title', 'description', 'captions')),
    reason text NOT NULL CHECK (reason IN ('csam', 'ncii', 'violence', 'malware', 'adult_unmarked', 'copyright',
        'harassment', 'spam', 'other', 'bug')),
    priority smallint NOT NULL CHECK (priority BETWEEN 0 AND 3),
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved', 'dismissed')),
    reporter_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    reporter_fingerprint bigint,
    reporter_abuse_ip_hash bytea,
    contact_email text CHECK (char_length(contact_email) <= 254),
    details text CHECK (char_length(details) <= 2000),
    dmca jsonb,
    case_id bigint REFERENCES moderation_cases (id) ON DELETE SET NULL,
    resolution_action text,
    reopen_count smallint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    reopened_at timestamptz,
    -- set by the report_closer 30 days after resolved_at: read only from then
    closed_at timestamptz,
    CHECK (kind <> 'bug' OR num_nonnulls(file_id, album_id, user_id) = 0),
    CHECK (num_nonnulls(file_id, album_id, user_id) <= 1),
    CHECK (kind = 'file' OR file_id IS NULL),
    CHECK (kind = 'album' OR album_id IS NULL),
    CHECK (kind = 'user' OR user_id IS NULL),
    CHECK ((kind = 'album') = (album_part IS NOT NULL))
);
CREATE INDEX reports_reporter ON reports (reporter_user_id, id DESC) WHERE reporter_user_id IS NOT NULL;
CREATE INDEX reports_case ON reports (case_id) WHERE case_id IS NOT NULL;
CREATE INDEX reports_file ON reports (file_id, reason) WHERE file_id IS NOT NULL AND status = 'open';
CREATE INDEX reports_album ON reports (album_id, reason) WHERE album_id IS NOT NULL AND status = 'open';
CREATE INDEX reports_user ON reports (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX reports_ip ON reports (id) WHERE reporter_abuse_ip_hash IS NOT NULL;

ALTER TABLE moderation_actions ADD FOREIGN KEY (report_id) REFERENCES reports (id) ON DELETE SET NULL;

CREATE TABLE report_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id bigint NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
    author_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    is_staff boolean NOT NULL DEFAULT false,
    body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX report_messages_report ON report_messages (report_id, id);

CREATE TABLE report_reads (
    report_id bigint NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    last_read_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (report_id, user_id)
);

-- scanner, report and owner flags, grouped into cases with the reports
CREATE TABLE content_flags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash_id bigint REFERENCES file_hashes (id) ON DELETE SET NULL,
    file_id bigint REFERENCES files (id) ON DELETE SET NULL,
    album_id bigint REFERENCES albums (id) ON DELETE SET NULL,
    source text NOT NULL CHECK (source IN ('scan', 'rescan', 'reports', 'owner')),
    -- a §2.3 code, or a report reason
    reason text NOT NULL,
    details jsonb,
    case_id bigint REFERENCES moderation_cases (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz
);
CREATE INDEX content_flags_case ON content_flags (case_id) WHERE case_id IS NOT NULL;
CREATE INDEX content_flags_hash ON content_flags (hash_id) WHERE hash_id IS NOT NULL AND resolved_at IS NULL;
CREATE INDEX content_flags_file ON content_flags (file_id) WHERE file_id IS NOT NULL;


-- rate limits and evidence (§7.7, §3.6) --------------------------------------------------------------------------

-- like unlock_attempts; windows older than an hour are deleted
CREATE TABLE safety_rate_limits (
    scope text NOT NULL CHECK (scope IN ('report', 'report_message')),
    -- user:<id>, fp:<fingerprint> or ip:<hex hash>
    key text NOT NULL CHECK (key ~ '^(user|fp|ip):[0-9a-f]+$'),
    window_start timestamptz NOT NULL,
    count integer NOT NULL DEFAULT 0,
    PRIMARY KEY (scope, key, window_start)
);
CREATE INDEX safety_rate_limits_window ON safety_rate_limits (window_start);

CREATE TABLE evidence_holds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint REFERENCES moderation_cases (id) ON DELETE SET NULL,
    hash_id bigint REFERENCES file_hashes (id) ON DELETE SET NULL,
    blake2b text NOT NULL,
    sha1 text NOT NULL,
    md5 text NOT NULL,
    size bigint,
    -- `files`: the blob stays in the files bucket (blob GC skips it); `evidence`: copied to the evidence bucket
    bucket text NOT NULL CHECK (bucket IN ('files', 'evidence')),
    storage_key text NOT NULL,
    reason text NOT NULL CHECK (reason IN ('csam', 'moderator')),
    retain_until timestamptz NOT NULL,
    snapshot jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    released_at timestamptz
);
CREATE INDEX evidence_holds_hash ON evidence_holds (hash_id) WHERE hash_id IS NOT NULL AND released_at IS NULL;

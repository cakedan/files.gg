export function isFixtureName(value: string | null): value is FixtureName {
  return value !== null && (FIXTURE_NAMES as readonly string[]).includes(value);
}

/**
 * Dev convenience: the fixture a path implies when no `?fixture=` is given, at the
 * Worker's paths (milestone-6 §20.2: `/report/<vanity>`, `/report/a/<vanity>`, and
 * `/a/<vanity>` with the lightbox item as `?item=<n>`).
 */
export function fixtureForPath(pathname: string): FixtureName | null {
  if (pathname === '/report' || pathname === '/report/') return 'report';
  if (/^\/report\/a\/[^/]+\/?$/.test(pathname)) return 'report-album';
  if (pathname.startsWith('/report/')) return 'report-file';
  if (/^\/a\/[^/]+\/?$/.test(pathname)) return 'album-grid';
  return null;
}

/** Injects a fixture into the document the way the worker would. */
export async function applyFixture(name: FixtureName, doc: Document = document, now = Date.now()): Promise<void> {
  const needsClip = name === 'video' || name === 'processing';
  const fixture = fixtures(now, { clip: needsClip ? await recordClip() : null })[name];
  const root = doc.getElementById('root');
  if (!root) return;
  if (fixture.page) root.dataset.page = fixture.page;
  if (fixture.state) root.dataset.state = fixture.state;

  doc.getElementById('file-data')?.remove();
  doc.getElementById('album-data')?.remove();
  doc.getElementById('report-data')?.remove();
  const inline = (id: string, value: unknown) => {
    const script = doc.createElement('script');
    script.id = id;
    script.type = 'application/json';
    script.textContent = JSON.stringify(value);
    root.after(script);
  };
  if (fixture.file !== undefined) inline('file-data', fixture.file);
  if (fixture.album !== undefined) inline('album-data', fixture.album);
  if (fixture.report !== undefined) inline('report-data', fixture.report);
}

/** The dev API's base, as lib/api resolves it (the mock unless VITE_API_URL says otherwise). */
function devApiBase(origin: string): string {
  const raw = import.meta.env.VITE_API_URL?.trim() || '/api';
  return new URL(raw, origin).href.replace(/\/+$/, '');
}


/**
 * Simulates a custom domain the way the Worker serves one (milestone-6 §10.9, §13.4):
 * `data-host="custom"`, `#host-data`, and every URL in the boot data rehosted. The
 * "custom domain" is this dev server itself; its API is the dev API (the mock), called
 * without credentials, and its challenge frame is this dev server's `/challenge`.
 */
export function applyCustomHost(doc: Document = document): void {
  const root = doc.getElementById('root');
  if (!root) return;
  const { origin, host } = doc.location;
  root.dataset.host = 'custom';
  doc.getElementById('host-data')?.remove();
  const data = doc.createElement('script');
  data.id = 'host-data';
  data.type = 'application/json';
  data.textContent = JSON.stringify({ host, main_origin: origin, api_origin: devApiBase(origin) });
  root.after(data);
  for (const id of ['file-data', 'album-data']) {
    const script = doc.getElementById(id);
    if (!script?.textContent) continue;
    try {
      const payload: unknown = JSON.parse(script.textContent);
      script.textContent = JSON.stringify(rehostPayload(payload, origin, ['https://cdn.files.gg', DEFAULT_MAIN_ORIGIN]));
    } catch {
      // Leave malformed fixtures alone.
    }
  }
}

const PLAIN = new Set(['', 'txt', 'text', 'plain', 'plaintext', 'plain_text']);

/** A known Shiki id for a language name or extension, or null. */
export function normalizeLanguage(value: string | undefined | null): LanguageId | null {
  if (!value) return null;
  const key = value.trim().toLowerCase();
  if (PLAIN.has(key)) return null;
  if (key in LANGUAGE_NAMES) return key as LanguageId;
  return ALIASES[key] ?? null;
}

/** `media.language`, else the filename or extension, else null (plain text). */
export function resolveLanguage(file: { filename: string; extension: string; media?: { language?: string | undefined } | undefined }): LanguageId | null {
  return (
    normalizeLanguage(file.media?.language) ??
    FILENAMES[file.filename.toLowerCase()] ??
    normalizeLanguage(file.extension) ??
    null
  );
}

